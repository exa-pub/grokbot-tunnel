func TestUnits(t *testing.T) {
	units, err := Units(systemd.Scope{User: true}, Config{
		Exe:     "/home/u/my bin/grokbot-tunnel",
		Args:    []string{"--permission", "always", "--root", "/srv/100% $HOME", "--label", `a "b" \c`},
		Env:     []string{"PATH=/home/u/.local/bin:/usr/bin", "SAND_BACKEND_URL=https://x.invalid/%41"},
		Version: "v1.2.3",
	})
	if err != nil || len(units) != 1 || units[TunnelUnit] != wantUserUnit {
		t.Fatalf("%v\n%s", err, units[TunnelUnit])
	}
	units, err = Units(systemd.Scope{}, Config{
		Exe: "/usr/local/bin/grokbot-tunnel", Args: []string{"--permission", "ask"}, Version: "v1.2.3", AutoUpdate: true,
	})
	if err != nil || units[TunnelUnit] != wantSystemUnit {
		t.Fatalf("%v\n%s", err, units[TunnelUnit])
	}
	if !strings.Contains(units[UpdateUnit], "User=root\nExecStart=/usr/local/bin/grokbot-tunnel update --auto\n") ||
		!strings.Contains(units[UpdateTimer], "OnCalendar=daily\n") || !strings.Contains(units[UpdateTimer], "WantedBy=timers.target\n") {
		t.Fatalf("%s\n%s", units[UpdateUnit], units[UpdateTimer])
	}
}

func TestQuoting(t *testing.T) {
	for _, tc := range []struct{ in, want string }{
		{"plain", "plain"},
		{"", `""`},
		{";", `";"`},
		{"it's", `"it's"`},
		{"${HOME}", "$${HOME}"},
		{"%h", "%%h"},
	} {
		if got, err := quoteExec([]string{tc.in}); err != nil || got != tc.want {
			t.Errorf("quoteExec(%q) = %q, %v; want %q", tc.in, got, err, tc.want)
		}
	}
	for _, bad := range []string{"a\nb", "a\tb", "\x7f"} {
		if _, err := quoteExec([]string{bad}); !errors.Is(err, errControl) {
			t.Errorf("quoteExec(%q): %v", bad, err)
		}
		if _, err := quoteEnv("K=" + bad); !errors.Is(err, errControl) {
			t.Errorf("quoteEnv(%q): %v", bad, err)
		}
	}
	if _, err := quoteExec([]string{"/home/caf\xe9"}); !errors.Is(err, errInvalidUTF8) {
		t.Errorf("invalid UTF-8 accepted: %v", err)
	}
	if got, err := quoteEnv("A=$x y"); err != nil || got != `"A=$x y"` {
		t.Error(got, err)
	}
	if _, err := quoteEnv("=x"); err == nil {
		t.Error("empty key accepted")
	}
}

func TestInstall(t *testing.T) {
	m, f, out := newFake(t, true)
	f.replies["loginctl show-user "+currentUser(t)+" --property=Linger --value"] = "no\n"
	c := Config{Exe: "/bin/gt", Args: []string{"--permission", "always"}, Version: "v1", AutoUpdate: true}
	if err := installUnits(context.Background(), m, c); err != nil {
		t.Fatal(err)
	}
	want := []string{
		"systemctl --user daemon-reload",
		"systemctl --user enable grokbot-tunnel.service",
		"systemctl --user enable --now grokbot-tunnel-update.timer",
		"loginctl show-user " + currentUser(t) + " --property=Linger --value",
		"loginctl enable-linger",
		"systemctl --user restart grokbot-tunnel.service",
	}
	if !slices.Equal(f.calls, want) {
		t.Fatalf("calls:\n%s", strings.Join(f.calls, "\n"))
	}
	if found, err := m.Existing(TunnelUnit, UpdateUnit, UpdateTimer); err != nil || len(found) != 3 {
		t.Fatal(found, err)
	}

	// Installing again without auto-update keeps the tunnel unit and drops the timer.
	out.Reset()
	f.calls = nil
	c.AutoUpdate = false
	if err := installUnits(context.Background(), m, c); err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(out.String(), "grokbot-tunnel.service is up to date") || f.calls[0] != "systemctl --user disable --now grokbot-tunnel-update.timer" {
		t.Fatal(out.String(), f.calls)
	}
	if found, _ := m.Existing(TunnelUnit, UpdateUnit, UpdateTimer); !slices.Equal(found, []string{TunnelUnit}) {
		t.Fatal(found)
	}
	entries, _ := os.ReadDir(m.Scope.Dir)
	if len(entries) != 1 {
		t.Fatal("temporary files left behind", entries)
	}
}

