func TestUninstall(t *testing.T) {
	m, f, out := newFake(t, true)
	envFile := filepath.Join(t.TempDir(), EnvFile)
	if removed, err := removeUnits(context.Background(), m, envFile); removed || err != nil || len(f.calls) != 0 {
		t.Fatal(removed, err, f.calls)
	}
	// A partial install: the tunnel and the update service, but no timer.
	// Stopping comes last, since it ends an uninstall run inside the service.
	os.MkdirAll(m.Scope.Dir, 0o755)
	for _, name := range []string{TunnelUnit, UpdateUnit} {
		os.WriteFile(filepath.Join(m.Scope.Dir, name), nil, 0o644)
	}
	f.replies["systemctl --user is-active grokbot-tunnel.service"] = "active\n"
	f.replies["systemctl --user is-active grokbot-tunnel-update.service"] = "inactive\n"
	os.WriteFile(envFile, nil, 0o600)
	if removed, err := removeUnits(context.Background(), m, envFile); !removed || err != nil {
		t.Fatal(removed, err, out.String())
	}
	if _, err := os.Stat(envFile); !errors.Is(err, os.ErrNotExist) {
		t.Fatal("environment file kept:", err)
	}
	want := []string{
		"systemctl --user is-active grokbot-tunnel.service",
		"systemctl --user is-active grokbot-tunnel-update.service",
		"systemctl --user disable grokbot-tunnel.service",
		"systemctl --user daemon-reload",
		"systemctl --user stop grokbot-tunnel.service",
		"systemctl --user reset-failed grokbot-tunnel.service",
	}
	if !slices.Equal(f.calls, want) {
		t.Fatal(f.calls)
	}
	if found, _ := m.Existing(TunnelUnit, UpdateUnit, UpdateTimer); len(found) != 0 {
		t.Fatal(found)
	}
}

// O3-2: the services reach the server the way install's shell does. The
// proxies and CA certificates go to both units, a proxy URL with credentials
// only to the environment file, readable only by its owner, and the output
// masks the credentials.
func TestInstallKeepsProxy(t *testing.T) {
	for _, k := range serviceEnv {
		t.Setenv(k, "")
	}
	t.Setenv("PATH", "/usr/bin")
	t.Setenv("HTTPS_PROXY", `http://user:pa$s"w@proxy.corp:3128`)
	t.Setenv("https_proxy", "token@proxy.corp:3128")
	t.Setenv("HTTP_PROXY", "http://proxy.corp:3128")
	t.Setenv("NO_PROXY", "localhost,.corp")
	t.Setenv("SSL_CERT_FILE", "/etc/corp-ca.pem")
	store := &staterepo.Store{Dir: filepath.Join(t.TempDir(), "store")}
	m, _, out := newFake(t, true)
	c := Config{Exe: "/bin/gt", Version: "v1", AutoUpdate: true}
	if err := keepEnv(&c, store, out); err != nil {
		t.Fatal(err)
	}
	if err := installUnits(context.Background(), m, c); err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{
		"The service runs with HTTPS_PROXY=http://user:***@proxy.corp:3128\n",
		"The service runs with https_proxy=***@proxy.corp:3128\n",
		"The service runs with HTTP_PROXY=http://proxy.corp:3128\n",
		"The service runs with SSL_CERT_FILE=/etc/corp-ca.pem\n",
	} {
		if !strings.Contains(out.String(), want) {
			t.Errorf("output lacks %q:\n%s", want, out.String())
		}
	}
	envFile := filepath.Join(store.Dir, EnvFile)
	network := "Environment=\"HTTP_PROXY=http://proxy.corp:3128\"\nEnvironment=\"NO_PROXY=localhost,.corp\"\n" +
		"Environment=\"SSL_CERT_FILE=/etc/corp-ca.pem\"\nEnvironmentFile=" + envFile + "\n"
	tunnel, _ := os.ReadFile(filepath.Join(m.Scope.Dir, TunnelUnit))
	update, _ := os.ReadFile(filepath.Join(m.Scope.Dir, UpdateUnit))
	if !strings.Contains(string(tunnel), "Environment=\"PATH=/usr/bin\"\n"+network) {
		t.Errorf("tunnel unit:\n%s", tunnel)
	}
	if !strings.HasSuffix(string(update), "ExecStart=/bin/gt update --auto\n"+network) {
		t.Errorf("update unit:\n%s", update)
	}
	for _, secret := range []string{"pa$s", "token"} {
		if strings.Contains(out.String()+string(tunnel)+string(update), secret) {
			t.Errorf("%q shown or in a unit", secret)
		}
	}
	b, err := os.ReadFile(envFile)
	want := header("v1") + `HTTPS_PROXY="http://user:pa\$s\"w@proxy.corp:3128"` + "\n" + `https_proxy="token@proxy.corp:3128"` + "\n"
	if err != nil || string(b) != want {
		t.Fatalf("%v\n%s", err, b)
	}
	if st, err := os.Stat(envFile); err != nil || st.Mode().Perm() != 0o600 {
		t.Fatal(st.Mode(), err)
	}

	// Without credentials the file is removed and the units do not name it.
	t.Setenv("HTTPS_PROXY", "")
	t.Setenv("https_proxy", "")
	c = Config{Exe: "/bin/gt", Version: "v1", AutoUpdate: true}
	if err := keepEnv(&c, store, out); err != nil || c.EnvFile != "" {
		t.Fatal(c.EnvFile, err)
	}
	if _, err := os.Stat(envFile); !errors.Is(err, os.ErrNotExist) {
		t.Fatal("environment file kept:", err)
	}
}

func TestMaskProxy(t *testing.T) {
	for _, tc := range []struct{ k, in, want string }{
		{"HTTPS_PROXY", "socks5://u:p@h:1080", "socks5://u:***@h:1080"},
		{"http_proxy", "u:p:q@h:3128", "u:***@h:3128"},
		{"HTTP_PROXY", "http://h:3128", "http://h:3128"},
		{"SSL_CERT_FILE", "/home/a@b/ca.pem", "/home/a@b/ca.pem"},
	} {
		if got := maskProxy(tc.k, tc.in); got != tc.want {
			t.Errorf("maskProxy(%s, %q) = %q; want %q", tc.k, tc.in, got, tc.want)
		}
	}
	if _, err := envFile("v1", []string{"HTTPS_PROXY=http://u:p\n@h"}); err == nil || strings.Contains(err.Error(), "u:p") {
		t.Error("secret in error:", err)
	}
}

// fakeSystem records commands and answers them from replies, keyed by the
// command line.
type fakeSystem struct {
	calls   []string
	replies map[string]string
	fail    map[string]bool
}

func (f *fakeSystem) run(_ context.Context, name string, args ...string) ([]byte, error) {
	line := strings.Join(append([]string{name}, args...), " ")
	f.calls = append(f.calls, line)
	if f.fail[line] {
		return nil, fmt.Errorf("%s failed", line)
	}
	return []byte(f.replies[line]), nil
}

func newFake(t *testing.T, user bool) (*systemd.Manager, *fakeSystem, *bytes.Buffer) {
	t.Helper()
	f := &fakeSystem{replies: map[string]string{}, fail: map[string]bool{}}
	var out bytes.Buffer
	return &systemd.Manager{Scope: systemd.Scope{User: user, Dir: filepath.Join(t.TempDir(), "units")}, Run: f.run, Out: &out}, f, &out
}

func currentUser(t *testing.T) string {
	t.Helper()
	u, err := user.Current()
	if err != nil {
		t.Fatal(err)
	}
	return u.Username
}
