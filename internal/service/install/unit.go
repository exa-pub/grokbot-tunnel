package install

import (
	"errors"
	"fmt"
	"slices"
	"strings"
	"unicode/utf8"

	"github.com/exa-pub/grokbot-tunnel/internal/adapter/systemd"
)

// Unit names. The tunnel unit is also what systemd.Owner looks for in a
// process's cgroup.
const (
	Name          = "grokbot-tunnel"
	TunnelUnit    = Name + ".service"
	UpdateUnit    = Name + "-update.service"
	UpdateTimer   = Name + "-update.timer"
	documentation = "https://github.com/exa-pub/grokbot-tunnel"
)

// ExitLogin is the exit status of connect when the user has to log in again.
// It is EX_CONFIG from sysexits.h, which systemd shows as "78/CONFIG".
const ExitLogin = 78

// Config describes the service to install.
type Config struct {
	Exe        string   // absolute path of the grokbot-tunnel binary
	Args       []string // connect arguments
	Env        []string // KEY=VALUE pairs for the tunnel; the update service gets those of networkEnv
	EnvFile    string   // absolute path of an environment file for both services, empty if none
	Version    string   // version of the binary generating the units
	AutoUpdate bool     // install the daily update timer
}

// Units renders the unit files for c in scope s, keyed by unit name. Without
// AutoUpdate the update units are left out.
func Units(s systemd.Scope, c Config) (map[string]string, error) {
	tunnel, err := tunnelUnit(s, c)
	if err != nil {
		return nil, err
	}
	units := map[string]string{TunnelUnit: tunnel}
	if !c.AutoUpdate {
		return units, nil
	}
	update, err := quoteExec([]string{c.Exe, "update", "--auto"})
	if err != nil {
		return nil, err
	}
	// The update downloads through the same proxy as the tunnel.
	env, err := environment(c, func(key string) bool { return slices.Contains(networkEnv, key) })
	if err != nil {
		return nil, err
	}
	units[UpdateUnit] = header(c.Version) + "[Unit]\nDescription=Update grokbot-tunnel\nDocumentation=" + documentation + "\n" +
		"\n[Service]\nType=oneshot\n" + unitUser(s) + "ExecStart=" + update + "\n" + env
	units[UpdateTimer] = header(c.Version) + "[Unit]\nDescription=Daily grokbot-tunnel update check\n" +
		"\n[Timer]\nOnCalendar=daily\nRandomizedDelaySec=1h\nPersistent=true\n" +
		"\n[Install]\nWantedBy=timers.target\n"
	return units, nil
}

func header(version string) string {
	return "# Generated by grokbot-tunnel " + version + " install. Re-run \"grokbot-tunnel install\"\n" +
		"# to change options; manual edits are overwritten.\n"
}

func tunnelUnit(s systemd.Scope, c Config) (string, error) {
	execStart, err := quoteExec(append([]string{c.Exe, "connect"}, c.Args...))
	if err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString(header(c.Version))
	b.WriteString("[Unit]\nDescription=Grok Bot tunnel\nDocumentation=" + documentation + "\n")
	// Restart forever: the tunnel may start before the network is up, and a
	// manual connect holding the instance lock may stop at any time.
	b.WriteString("StartLimitIntervalSec=0\n")
	if !s.User {
		// The user manager has no network-online.target to wait for.
		b.WriteString("After=network-online.target\nWants=network-online.target\n")
	}
	b.WriteString("\n[Service]\nType=notify\nTimeoutStartSec=60s\n")
	b.WriteString(unitUser(s))
	b.WriteString("ExecStart=" + execStart + "\n")
	env, err := environment(c, func(string) bool { return true })
	if err != nil {
		return "", err
	}
	b.WriteString(env)
	// Retrying cannot help a user who has to log in again.
	fmt.Fprintf(&b, "Restart=on-failure\nRestartSec=10s\nRestartPreventExitStatus=%d\n", ExitLogin)
	b.WriteString("\n[Install]\nWantedBy=" + wantedBy(s) + "\n")
	return b.String(), nil
}

// environment renders an Environment= line for each pair of c.Env whose key
// keep accepts, and EnvironmentFile= for c.EnvFile, if any.
func environment(c Config, keep func(key string) bool) (string, error) {
	var b strings.Builder
	for _, kv := range c.Env {
		if k, _, _ := strings.Cut(kv, "="); !keep(k) {
			continue
		}
		v, err := quoteEnv(kv)
		if err != nil {
			return "", err
		}
		b.WriteString("Environment=" + v + "\n")
	}
	if c.EnvFile != "" {
		if err := checkValue(c.EnvFile); err != nil {
			return "", err
		}
		// The path is taken verbatim, specifiers aside.
		b.WriteString("EnvironmentFile=" + strings.ReplaceAll(c.EnvFile, "%", "%%") + "\n")
	}
	return b.String(), nil
}

// user sets the account of system units explicitly, since only then does
// systemd set HOME, which locates the store.
func unitUser(s systemd.Scope) string {
	if s.User {
		return ""
	}
	return "User=root\n"
}

func wantedBy(s systemd.Scope) string {
	if s.User {
		return "default.target"
	}
	return "multi-user.target"
}

// quoteExec renders args as an ExecStart= command line. Specifiers (%) and
// environment variable references ($) are escaped so that every argument is
// passed literally.
func quoteExec(args []string) (string, error) {
	words := make([]string, len(args))
	for i, a := range args {
		if err := checkValue(a); err != nil {
			return "", err
		}
		a = strings.ReplaceAll(strings.ReplaceAll(a, "%", "%%"), "$", "$$")
		if a == "" || strings.ContainsAny(a, " \t\"'\\;") {
			a = quote(a)
		}
		words[i] = a
	}
	return strings.Join(words, " "), nil
}

// quoteEnv renders a KEY=VALUE pair for Environment=, which expands
// specifiers but not variables.
func quoteEnv(kv string) (string, error) {
	if err := checkValue(kv); err != nil {
		return "", err
	}
	if k, _, ok := strings.Cut(kv, "="); !ok || k == "" {
		return "", fmt.Errorf("invalid environment entry %q", kv)
	}
	return quote(strings.ReplaceAll(kv, "%", "%%")), nil
}

// envFileEscaper escapes the characters a backslash escapes in a
// double-quoted value of an environment file.
var envFileEscaper = strings.NewReplacer(`\`, `\\`, `"`, `\"`, "`", "\\`", "$", `\$`)

// envFile renders KEY=VALUE pairs as an EnvironmentFile=, which systemd reads
// like double-quoted shell assignments: a backslash escapes ", \, ` and $,
// and neither specifiers nor variables are expanded. The pairs are secret,
// so errors name only their keys.
func envFile(version string, env []string) (string, error) {
	var b strings.Builder
	b.WriteString(header(version))
	for _, kv := range env {
		k, v, ok := strings.Cut(kv, "=")
		if !ok || k == "" {
			return "", errors.New("invalid environment entry")
		}
		if err := checkValue(kv); err != nil {
			return "", fmt.Errorf("%s: %w", k, errors.Unwrap(err))
		}
		b.WriteString(k + `="` + envFileEscaper.Replace(v) + "\"\n")
	}
	return b.String(), nil
}

func quote(s string) string {
	return `"` + strings.ReplaceAll(strings.ReplaceAll(s, `\`, `\\`), `"`, `\"`) + `"`
}

// checkValue rejects control characters, which unit files cannot carry
// without escapes that systemd would interpret, and invalid UTF-8, which
// systemd does not take in a setting.
func checkValue(s string) error {
	if !utf8.ValidString(s) {
		return fmt.Errorf("%q: %w", s, errInvalidUTF8)
	}
	if strings.ContainsFunc(s, func(r rune) bool { return r < 0x20 || r == 0x7f }) {
		return fmt.Errorf("%q: %w", s, errControl)
	}
	return nil
}

var (
	errControl     = errors.New("control characters are not allowed in service settings")
	errInvalidUTF8 = errors.New("service settings must be valid UTF-8")
)
